"""`repro venue acm-evidence`: the records bearing on each criterion of ACM's badging policy.

For each criterion of ACM Artifact Review and Badging, version 1.1, this lists the findings
of the readers that bear on it, and says nothing about whether the criterion is met: that is
an evaluator's judgment, made by people, and a list of records is not one. The criteria's text
is the policy's, copied verbatim into `data/acm_badging.json` with where and when it was read.

Two criteria concern the main results being obtained by a person or team other than the
authors. No record in the authors' repository can show that, so each is reported as not
determinable by this tool, with no findings, whatever the repository holds.

The output never uses a badge's name or image as a label or a status. Its label is `LABEL`,
and each criterion's standing is one of `Standing`: records listed, no record found, or not
determinable by this tool.
"""

from __future__ import annotations

import enum
import html
import importlib.resources
import json

from pydantic import BaseModel, ConfigDict, computed_field

from repro import __version__
from repro.venue.draft import Source, Status
from repro.venue.records import READERS, Finding, Project, spans

#: What the output is, in every format, word for word.
LABEL = "Evidence mapped to ACM Artifact Review and Badging v1.1 criteria; not an ACM badge."

#: For each criterion an author's records can bear on, the readers whose findings do.
READS: dict[str, tuple[str, ...]] = {
    "archival": ("archive",),
    "exercisable": ("regenerations", "reruns", "claims", "documentation"),
    "reuse": ("regenerations", "reruns", "claims", "documentation", "license", "environment"),
}

NOT_DETERMINABLE_WHY = (
    "The policy requires the main results to be obtained by a person or team other than the "
    "authors. No record in the authors' repository can show that."
)


class Criterion(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    id: str
    title: str
    """This package's short description, never the name of a badge."""
    policy_text: str
    """The policy's own words for the criterion, verbatim."""
    determinable: bool
    """Whether records in the authors' repository can bear on it at all."""
    source_line: int
    """The line of the saved policy text the quotation is on."""
    quoted_sha256: str
    """The sha256 of `policy_text` in UTF-8, so the quotation can be checked against a copy
    of the page saved independently."""


class Policy(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    name: str
    version: str
    source: Source
    criteria: tuple[Criterion, ...]


class Standing(enum.StrEnum):
    LISTED = "records listed"
    """At least one record bears on the criterion. Nothing is said about whether it is met."""
    NONE = "no record found"
    NOT_DETERMINABLE = "not determinable by this tool"


#: The status each standing is shown with. A list of records is a draft for the authors and
#: the evaluators to read; where nothing is listed, the criterion is left to them.
STATUS = {
    Standing.LISTED: Status.DRAFT,
    Standing.NONE: Status.TODO,
    Standing.NOT_DETERMINABLE: Status.TODO,
}

#: The header's mark, on every page and in every JSON document.
DRAFT_HEADER = (
    "DRAFT. Generated by a program from the records in this repository and not reviewed by "
    "the authors. Each criterion is marked DRAFT where records are listed and TODO where none "
    "is."
)


class Mapped(BaseModel):
    """One criterion and the findings that bear on it."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    criterion: Criterion
    standing: Standing
    findings: tuple[Finding, ...] = ()
    note: str = ""

    @computed_field
    @property
    def records(self) -> tuple[str, ...]:
        return tuple(dict.fromkeys(finding.record for finding in self.findings))

    @computed_field
    @property
    def status(self) -> Status:
        return STATUS[self.standing]


class EvidenceMap(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    label: str = LABEL
    status: Status = Status.DRAFT
    draft_notice: str = DRAFT_HEADER
    policy: Policy
    generated_by: str
    criteria: tuple[Mapped, ...]


def policy() -> Policy:
    text = (
        importlib.resources.files("repro.venue")
        .joinpath("data", "acm_badging.json")
        .read_text(encoding="utf-8")
    )
    return Policy.model_validate(json.loads(text))


def evidence_map(project: Project) -> EvidenceMap:
    stored = policy()
    wanted = dict.fromkeys(reader for readers in READS.values() for reader in readers)
    found = {reader: READERS[reader](project) for reader in wanted}
    mapped = []
    for criterion in stored.criteria:
        if not criterion.determinable:
            mapped.append(
                Mapped(
                    criterion=criterion,
                    standing=Standing.NOT_DETERMINABLE,
                    note=NOT_DETERMINABLE_WHY,
                )
            )
            continue
        findings = tuple(f for reader in READS[criterion.id] for f in found[reader])
        mapped.append(
            Mapped(
                criterion=criterion,
                standing=Standing.LISTED if findings else Standing.NONE,
                findings=findings,
            )
        )
    return EvidenceMap(policy=stored, generated_by=f"repro {__version__}", criteria=tuple(mapped))


def as_json(made: EvidenceMap) -> str:
    return made.model_dump_json(indent=2) + "\n"


_STYLE = """
body { font-family: system-ui, sans-serif; max-width: 52rem; margin: 2rem auto;
  padding: 0 1rem; line-height: 1.5; color: #1f2328; background: #ffffff; }
blockquote { margin: 0.5rem 0; padding-left: 1rem; border-left: 3px solid #d0d7de; }
.standing, .draft { font-weight: 600; }
code { font-size: 0.9em; }
""".strip()


def _code_spans(text: str) -> str:
    """A finding's words, escaped, with each Markdown code span as code."""
    return "".join(
        f"<code>{html.escape(part)}</code>" if is_code else html.escape(part)
        for is_code, part in spans(text)
    )


def as_html(made: EvidenceMap) -> str:
    """One page: the label, where the policy text was read, and each criterion with its
    standing and the findings that bear on it. No image."""
    source = made.policy.source
    out = [
        "<!doctype html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        f"<title>{html.escape(made.label)}</title>",
        f"<style>{_STYLE}</style>",
        "</head>",
        "<body>",
        "<header>",
        f'<p class="draft"><strong>{html.escape(made.draft_notice)}</strong></p>',
        f"<h1>{html.escape(made.label)}</h1>",
        "</header>",
        "<p>Generated by "
        f"{html.escape(made.generated_by)} from the records in this repository. For each "
        "criterion it lists the records that bear on it. Whether a criterion is met is decided "
        "by evaluators, not by this page.</p>",
        f'<p>Policy text read from <a href="{html.escape(source.url)}">'
        f"{html.escape(source.url)}</a> on {source.retrieved}.</p>",
    ]
    for mapped in made.criteria:
        criterion = mapped.criterion
        out += [
            f'<section id="{html.escape(criterion.id)}">',
            f"<h2>{html.escape(criterion.title)}</h2>",
            f"<blockquote>{html.escape(criterion.policy_text)}</blockquote>",
            f'<p class="standing">{mapped.status.value.upper()}: '
            f"{html.escape(mapped.standing.value)}</p>",
        ]
        if mapped.note:
            out.append(f"<p>{html.escape(mapped.note)}</p>")
        if mapped.findings:
            out.append("<ul>")
            out += [
                f"<li><code>{html.escape(f.record)}</code> {_code_spans(f.said)}</li>"
                for f in mapped.findings
            ]
            out.append("</ul>")
        out.append("</section>")
    out += ["</body>", "</html>"]
    return "\n".join(out) + "\n"


__all__ = ["LABEL", "READS", "EvidenceMap", "Standing", "as_html", "as_json", "evidence_map"]
