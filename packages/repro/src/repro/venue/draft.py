"""A venue's questions, answered from the records where a record answers them, and marked so.

A questionnaire is what a venue asks, stored as data with the address it was copied from and
the day it was copied: the text of each question is the venue's, never this package's. A draft
pairs each question with the findings the venue's readers return for it. A question with
findings is a `draft`: every line under it was generated from the record it names, and the
authors have yet to read it. A question with none is a `todo`, left for the authors and never
filled with generated prose. Where a venue asks for yes or no, the choice is the authors',
except where a record settles it with no judgment involved: a DOI in `CITATION.cff` settles
whether the artifacts are archived. Such a choice is named in the venue's `SETTLES`, is still a
draft, and names the record that settles it.

A draft that reads as authored is the defect this exists to prevent, the same defect as an
inferred claim counted as verified, so every rendering marks every generated line.
"""

from __future__ import annotations

import datetime
import enum
import importlib.resources
import json
from collections.abc import Mapping

from pydantic import BaseModel, ConfigDict, computed_field

from repro import __version__
from repro.exceptions import ReproError
from repro.venue.records import READERS, Finding, Project

#: The banner every rendering opens with.
DRAFT_NOTICE = (
    "DRAFT. Generated by repro {version} from the records in this repository. Every answer "
    "marked DRAFT was written by a program from the record it names, not by the authors: "
    "check each against the paper before submitting. Every answer marked TODO is a question "
    "no record here answers; the authors write it."
)


class Source(BaseModel):
    """Where a questionnaire's text was copied from, and when."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    url: str
    retrieved: datetime.date
    sha256: str = ""
    """Of the bytes the text was copied from, where they were saved."""
    via: str
    """How the bytes were obtained, and what was copied from them."""


class Question(BaseModel):
    """One question, in the venue's words."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    id: str
    section: str = ""
    title: str
    text: str = ""


class Questionnaire(BaseModel):
    """Everything one venue asks, in its order."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    venue: str
    name: str
    source: Source
    questions: tuple[Question, ...]

    def question(self, question_id: str) -> Question:
        found = next((q for q in self.questions if q.id == question_id), None)
        if found is None:
            raise UnknownQuestionError(self.venue, question_id)
        return found


class UnknownQuestionError(ReproError):
    """A venue's mapping names a question its questionnaire does not hold."""

    def __init__(self, venue: str, question_id: str) -> None:
        super().__init__(f"{venue}: no question {question_id!r} in the stored questionnaire")


class UnknownReaderError(ReproError):
    """A venue's mapping names a reader `repro.venue.records` does not have."""

    def __init__(self, venue: str, reader: str) -> None:
        super().__init__(f"{venue}: no reader {reader!r} in repro.venue.records.READERS")


class Status(enum.StrEnum):
    DRAFT = "draft"
    """Generated from the records named, and not yet read by the authors."""
    TODO = "todo"
    """No record answers this question. The authors write the answer."""


class Settle(BaseModel):
    """A choice a record settles: made where any of `readers` finds anything."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    choice: str
    readers: tuple[str, ...]
    note: str = ""
    """Shown with the choice: what the authors must still confirm."""
    unsettled: str = ""
    """Shown where nothing settles it, in place of the plain TODO."""


class Answer(BaseModel):
    """One question and what the records say that bears on it."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    question: Question
    status: Status
    findings: tuple[Finding, ...] = ()
    choice: str = ""
    """A yes or no a record settles, as the venue words it. Empty where the authors choose."""
    choice_from: tuple[str, ...] = ()
    """The records that settle `choice`."""
    choice_note: str = ""
    """What the authors must still confirm about `choice`, which no record can settle."""
    todo_note: str = ""
    """Why the question is left to do, where the venue says more than that no record answers it."""

    @computed_field
    @property
    def records(self) -> tuple[str, ...]:
        """The records the findings were read from, each once, in the order first named."""
        return tuple(dict.fromkeys(finding.record for finding in self.findings))


class Draft(BaseModel):
    """A questionnaire with every question either drafted from a record or left to do."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    venue: str
    name: str
    source: Source
    generated_by: str
    notice: str
    answers: tuple[Answer, ...]

    def answer(self, question_id: str) -> Answer:
        return next(answer for answer in self.answers if answer.question.id == question_id)


def questionnaire(name: str) -> Questionnaire:
    """The stored questionnaire `repro/venue/data/<name>.json`."""
    text = (
        importlib.resources.files("repro.venue")
        .joinpath("data", f"{name}.json")
        .read_text(encoding="utf-8")
    )
    return Questionnaire.model_validate(json.loads(text))


def check_reads(stored: Questionnaire, reads: Mapping[str, tuple[str, ...]]) -> None:
    """Raise where a mapping names a question or a reader that does not exist."""
    for question_id, readers in reads.items():
        stored.question(question_id)
        for reader in readers:
            if reader not in READERS:
                raise UnknownReaderError(stored.venue, reader)


def fill(
    stored: Questionnaire,
    reads: Mapping[str, tuple[str, ...]],
    project: Project,
    settles: Mapping[str, Settle] | None = None,
) -> Draft:
    """Each question, with the findings of the readers `reads` names for it. A question with
    no finding is left to do.

    `settles` maps a question to a choice and the readers whose findings settle it: where any
    of them finds anything, the choice is made, and its findings are listed with the rest."""
    settles = settles or {}
    check_reads(stored, {**reads, **{q: settle.readers for q, settle in settles.items()}})
    wanted = dict.fromkeys(
        [
            *(r for readers in reads.values() for r in readers),
            *(r for settle in settles.values() for r in settle.readers),
        ]
    )
    found = {reader: READERS[reader](project) for reader in wanted}
    answers = []
    for question in stored.questions:
        findings = tuple(f for reader in reads.get(question.id, ()) for f in found[reader])
        settle = settles.get(question.id)
        settling = tuple(f for r in settle.readers for f in found[r]) if settle else ()
        findings += tuple(f for f in settling if f not in findings)
        answers.append(
            Answer(
                question=question,
                status=Status.DRAFT if findings else Status.TODO,
                findings=findings,
                choice=settle.choice if settle and settling else "",
                choice_from=tuple(dict.fromkeys(f.record for f in settling)),
                choice_note=settle.note if settle and settling else "",
                todo_note=settle.unsettled if settle and not settling else "",
            )
        )
    return Draft(
        venue=stored.venue,
        name=stored.name,
        source=stored.source,
        generated_by=f"repro {__version__}",
        notice=DRAFT_NOTICE.format(version=__version__),
        answers=tuple(answers),
    )


# ---------------------------------------------------------------------------------- Markdown


def _marker(answer: Answer) -> str:
    if answer.status is Status.TODO:
        why = answer.todo_note or "no record in this repository answers this."
        return f"**TODO** (authors): {why}"
    named = ", ".join(f"`{record}`" for record in answer.records)
    return f"**DRAFT**, generated from {named}; not written by the authors."


def choice_line(answer: Answer) -> str:
    """The answer a record settles, marked as a draft and naming the record."""
    named = ", ".join(f"`{record}`" for record in answer.choice_from)
    note = f"; {answer.choice_note}" if answer.choice_note else ""
    return f"Answer: **{answer.choice}** (DRAFT, settled by {named}{note})"


def _finding_line(finding: Finding) -> str:
    return f"- `{finding.record}` {finding.said}"


def markdown(draft: Draft) -> str:
    """The draft as Markdown: each question under its section, then its marker and findings."""
    lines = [
        f"# {draft.name} (DRAFT)",
        "",
        f"> {draft.notice}",
        "",
        f"Questions copied from {draft.source.url}, retrieved {draft.source.retrieved}.",
    ]
    section = None
    for answer in draft.answers:
        question = answer.question
        if not question.section:
            section = None
            lines += ["", f"## {question.title}"]
        else:
            if question.section != section:
                section = question.section
                lines += ["", f"## {section}"]
            lines += ["", f"### {question.title}"]
        if question.text:
            lines += ["", f"*{question.text}*"]
        if answer.choice:
            lines += ["", choice_line(answer)]
        lines += ["", _marker(answer)]
        if answer.findings:
            lines += ["", *(_finding_line(f) for f in answer.findings)]
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------------------------- LaTeX

_LATEX = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def latex_escape(text: str) -> str:
    """Text as LaTeX prints it, with every character LaTeX reads as markup escaped."""
    return "".join(_LATEX.get(char, char) for char in text)


def latex_code(text: str) -> str:
    """Text set in typewriter type, escaped. A backtick-quoted span in a finding becomes this."""
    return r"\texttt{" + latex_escape(text) + "}"


def latex_said(text: str) -> str:
    """A finding's words, with each backtick-quoted span in typewriter type."""
    parts = text.split("`")
    return "".join(
        latex_code(part) if index % 2 else latex_escape(part) for index, part in enumerate(parts)
    )


def latex_marker(answer: Answer) -> str:
    if answer.status is Status.TODO:
        why = latex_escape(answer.todo_note or "no record in this repository answers this.")
        return rf"\textbf{{[TODO (authors): {why}]}}"
    named = ", ".join(latex_code(record) for record in answer.records)
    marker = rf"\textbf{{[DRAFT, generated from {named}; not written by the authors.]}}"
    if answer.choice:
        settled = ", ".join(latex_code(record) for record in answer.choice_from)
        marker = (
            rf"{latex_escape(answer.choice)} \textbf{{[DRAFT, settled by {settled}"
            + (f"; {latex_escape(answer.choice_note)}" if answer.choice_note else "")
            + "]} "
            + marker
        )
    return marker


def latex_findings(answer: Answer) -> str:
    if not answer.findings:
        return ""
    items = "\n".join(
        rf"  \item {latex_code(f.record)} {latex_said(f.said)}" for f in answer.findings
    )
    return "\\begin{itemize}\n" + items + "\n\\end{itemize}"


def as_json(draft: Draft) -> str:
    return draft.model_dump_json(indent=2) + "\n"


